import h5py
import os
from tqdm import tqdm
import numpy as np


if __name__ == '__main__':
    # get h5 file path
    # 1979 ~ 2020
    file_paths = [os.path.join('./train', i) for i in sorted(os.listdir('./train'))]


    # get h5 file
    total_sum_diff = np.zeros(71, dtype=np.float64)
    total_sum_diff_squared = np.zeros(71, dtype=np.float64)
    total_sum_n = 0
    with tqdm(total=len(file_paths)) as pbar:
        for file in file_paths:
            with h5py.File(file, 'r') as f:
                data = f['fields'][...]
                # time difference
                diff = data[1:] - data[:-1]
                # get sum
                total_sum_diff += diff.sum(axis=(0, 2, 3))
                total_sum_diff_squared += (diff ** 2).sum(axis=(0, 2, 3))
                total_sum_n += (diff.shape[0] * diff.shape[2] * diff.shape[3])
                pbar.update(1)

    diff_mean = total_sum_diff / total_sum_n
    diff_std = np.sqrt((total_sum_diff_squared / total_sum_n) - (diff_mean ** 2))
    diff_mean = diff_mean.reshape(1, 71, 1, 1)
    diff_std = diff_std.reshape(1, 71, 1, 1)
    np.save('./stats_haotian_region/time_diff_means.npy', diff_mean)
    np.save('./stats_haotian_region/time_diff_stds.npy', diff_std)


